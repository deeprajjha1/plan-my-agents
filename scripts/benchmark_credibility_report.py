#!/usr/bin/env python3
"""Generate the per-capability credibility report.

Stage 0 of the trust-layer credibility roadmap. Walks every capability that
has at least one declared candidate, runs the credibility classifier, and
writes a Markdown report under `reports/benchmark-credibility/`.

The report is the artefact we point readers at when they ask "which
leaderboards do you stand behind?" Today the answer should be: zero
publishable, the rest are smoke tests. That honesty is the point.

Read-only. No store mutation. Safe to run in CI.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps" / "api"))

from planmyagents_api.benchmark.credibility import (  # noqa: E402
    classify_index,
    thresholds_from_env,
)
from planmyagents_api.benchmark.store import benchmark_store_for_path  # noqa: E402
from planmyagents_api.discovery.models import DiscoveryCandidate  # noqa: E402
from planmyagents_api.discovery.store import discovery_store_for_path  # noqa: E402

STATUS_BADGES: dict[str, str] = {
    "publishable": "PUBLISHABLE",
    "developing": "DEVELOPING",
    "smoke_test": "SMOKE TEST",
    "synthetic_only": "SYNTHETIC",
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--discovery-store",
        default=os.getenv(
            "PLANMYAGENTS_DISCOVERY_STORE_URL",
            str(ROOT / ".planmyagents_runs" / "discovery-store.sqlite"),
        ),
    )
    parser.add_argument(
        "--benchmark-store",
        default=os.getenv(
            "PLANMYAGENTS_BENCHMARK_STORE_URL",
            str(ROOT / ".planmyagents_runs" / "benchmark-store.json"),
        ),
    )
    parser.add_argument(
        "--out-dir",
        default=str(ROOT / "reports" / "benchmark-credibility"),
        help="Directory to write the dated Markdown report.",
    )
    parser.add_argument(
        "--also-json",
        action="store_true",
        help="Also write a JSON snapshot alongside the Markdown report.",
    )
    args = parser.parse_args()

    candidates: list[DiscoveryCandidate] = discovery_store_for_path(
        args.discovery_store
    ).load()
    rankings: list[dict[str, Any]] = list(
        benchmark_store_for_path(args.benchmark_store).load_rankings()
    )

    candidates_by_capability: dict[str, list[DiscoveryCandidate]] = {}
    for candidate in candidates:
        for capability in candidate.capabilities:
            candidates_by_capability.setdefault(capability.id, []).append(candidate)

    thresholds = thresholds_from_env()
    verdicts = classify_index(
        candidates_by_capability=candidates_by_capability,
        rankings=rankings,
    )

    counts = {status: 0 for status in STATUS_BADGES}
    for verdict in verdicts.values():
        counts[verdict.status] = counts.get(verdict.status, 0) + 1

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    today = datetime.now(UTC).strftime("%Y-%m-%d")
    md_path = out_dir / f"{today}.md"

    lines: list[str] = []
    lines.append(f"# Benchmark credibility report — {today}")
    lines.append("")
    lines.append("> Auto-generated by `make benchmark-credibility-report`.")
    lines.append("> Source of truth: discovery store + agent_rankings table.")
    lines.append("")
    lines.append("## Headline")
    lines.append("")
    lines.append(
        f"- **{counts.get('publishable', 0)} publishable** out of {len(verdicts)} "
        "capabilities. These are the only leaderboards we will defend externally."
    )
    lines.append(f"- {counts.get('developing', 0)} developing.")
    lines.append(f"- {counts.get('smoke_test', 0)} smoke test.")
    lines.append(f"- {counts.get('synthetic_only', 0)} synthetic only.")
    lines.append("")
    lines.append("## Thresholds in effect")
    lines.append("")
    lines.append(
        f"- Real-adapter providers per capability: ≥ {thresholds.min_real_providers}"
    )
    lines.append(
        f"- Real samples on at least one provider:  ≥ {thresholds.min_sample_size}"
    )
    lines.append(
        f"- Run age:                                 ≤ {thresholds.max_run_age_days} days"
    )
    lines.append("")
    lines.append("Override via environment variables:")
    lines.append(
        "`PLANMYAGENTS_CREDIBILITY_MIN_REAL_PROVIDERS`, "
        "`PLANMYAGENTS_CREDIBILITY_MIN_SAMPLE_SIZE`, "
        "`PLANMYAGENTS_CREDIBILITY_MAX_RUN_AGE_DAYS`."
    )
    lines.append("")

    for status_key in ("publishable", "developing", "smoke_test", "synthetic_only"):
        section_verdicts = sorted(
            (v for v in verdicts.values() if v.status == status_key),
            key=lambda v: v.capability,
        )
        if not section_verdicts:
            continue
        lines.append(f"## {STATUS_BADGES[status_key]} ({len(section_verdicts)})")
        lines.append("")
        for verdict in section_verdicts:
            lines.append(f"### `{verdict.capability}`")
            lines.append("")
            lines.append(
                f"- Real providers: **{verdict.real_provider_count}** "
                f"of {verdict.total_provider_count} candidates"
            )
            lines.append(f"- Max real sample size: {verdict.max_real_sample_size}")
            if verdict.last_real_run_at:
                lines.append(f"- Last real run at: {verdict.last_real_run_at}")
            if verdict.reasons:
                lines.append("- Reasons:")
                for reason in verdict.reasons:
                    lines.append(f"  - {reason}")
            if verdict.unblockers:
                lines.append("- Unblockers:")
                for unblocker in verdict.unblockers:
                    lines.append(f"  - {unblocker}")
            lines.append("")

    md_path.write_text("\n".join(lines))
    print(f"Wrote {md_path}")

    if args.also_json:
        json_path = md_path.with_suffix(".json")
        json_path.write_text(
            json.dumps(
                {
                    "generated_at": today,
                    "thresholds": {
                        "min_real_providers": thresholds.min_real_providers,
                        "min_sample_size": thresholds.min_sample_size,
                        "max_run_age_days": thresholds.max_run_age_days,
                    },
                    "counts": counts,
                    "verdicts": [
                        verdict.to_json() for verdict in verdicts.values()
                    ],
                },
                indent=2,
                sort_keys=True,
            )
        )
        print(f"Wrote {json_path}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
